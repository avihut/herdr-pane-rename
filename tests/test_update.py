from pathlib import Path
from types import SimpleNamespace
from unittest.mock import patch
import contextlib
import io
import json
import sys
import tempfile
import unittest
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))
import install

HEALTHY = SimpleNamespace(stdout='{"errors": []}')


def quietly(fn, *args, status=HEALTHY, **kwargs):
    with patch.object(install.subprocess, 'run', return_value=status) as run, contextlib.redirect_stdout(io.StringIO()):
        fn(*args, **kwargs)
    return run


def installed_home(tmp):
    """A temp home after a real install, with the app's generated files beside the mods."""
    home = Path(tmp)
    (home / 'layouts').mkdir()
    (home / 'keys.json').write_bytes(b'{"global":{"f2":"tab.rename"}}\n')
    with patch.object(sys, 'argv', ['install.py', '--home', str(home)]):
        quietly(install.main)
    for mod in install.OWNED:
        (home / 'mods' / mod / 'gpui-kit.d.ts').write_text('// generated by Herdr\n')
    return home


def manifest(home):
    return json.loads((home / '.pane-rename-backup/manifest.json').read_text())


class Update(unittest.TestCase):
    def age(self, home, rel, data):
        """Simulate an installation made from older source: installed bytes and their recorded hash."""
        (home / rel).write_bytes(data)
        doc = manifest(home)
        doc[rel]['installed'] = install.digest(data)
        (home / '.pane-rename-backup/manifest.json').write_bytes(install.encoded(doc))

    def test_deploys_only_changed_folders_and_keeps_generated_files(self):
        with tempfile.TemporaryDirectory() as tmp:
            home = installed_home(tmp)
            self.age(home, 'mods/pane-rename-menu/look.js', b'// old look\n')
            untouched = (home / 'mods/pane-rename').stat().st_ino
            before = manifest(home)
            quietly(install.update, home)
            source = (install.ROOT / 'mods/pane-rename-menu/look.js').read_bytes()
            self.assertEqual((home / 'mods/pane-rename-menu/look.js').read_bytes(), source)
            self.assertEqual((home / 'mods/pane-rename-menu/gpui-kit.d.ts').read_text(), '// generated by Herdr\n')
            # An unchanged mod is never swapped, so the host does not reload it.
            self.assertEqual((home / 'mods/pane-rename').stat().st_ino, untouched)
            after = manifest(home)
            self.assertEqual(after['mods/pane-rename-menu/look.js']['installed'], install.digest(source))
            self.assertEqual({k: v for k, v in after.items() if k != 'mods/pane-rename-menu/look.js'},
                             {k: v for k, v in before.items() if k != 'mods/pane-rename-menu/look.js'})
            self.assertFalse((home / '.pane-rename-backup/.staging/pane-rename-menu.previous').exists())
            # The installation stays uninstallable after an update.
            install.uninstall(home)
            self.assertFalse((home / 'mods/pane-rename-menu/look.js').exists())

    def test_refuses_when_an_owned_file_was_edited_after_install(self):
        with tempfile.TemporaryDirectory() as tmp:
            home = installed_home(tmp)
            self.age(home, 'mods/pane-rename/look.js', b'// old look\n')
            (home / 'mods/pane-rename-header/main.js').write_bytes(b'// someone else\n')
            before = manifest(home)
            with self.assertRaisesRegex(ValueError, 'pane-rename-header/main.js changed since installation'):
                quietly(install.update, home)
            self.assertEqual((home / 'mods/pane-rename/look.js').read_bytes(), b'// old look\n')
            self.assertEqual((home / 'mods/pane-rename-header/main.js').read_bytes(), b'// someone else\n')
            self.assertEqual(manifest(home), before)

    def test_refuses_to_reload_while_the_app_reports_errors(self):
        with tempfile.TemporaryDirectory() as tmp:
            home = installed_home(tmp)
            self.age(home, 'mods/pane-rename/look.js', b'// old look\n')
            sick = SimpleNamespace(stdout='{"errors": ["mods/winxp: out of memory"]}')
            with self.assertRaisesRegex(ValueError, 'out of memory'):
                quietly(install.update, home, status=sick)
            self.assertEqual((home / 'mods/pane-rename/look.js').read_bytes(), b'// old look\n')

    def test_matching_installation_is_a_no_op(self):
        with tempfile.TemporaryDirectory() as tmp:
            home = installed_home(tmp)
            inodes = {mod: (home / 'mods' / mod).stat().st_ino for mod in install.OWNED}
            run = quietly(install.update, home)
            run.assert_not_called()
            self.assertEqual({mod: (home / 'mods' / mod).stat().st_ino for mod in install.OWNED}, inodes)

    def test_leftover_staging_is_reported_not_overwritten(self):
        with tempfile.TemporaryDirectory() as tmp:
            home = installed_home(tmp)
            self.age(home, 'mods/pane-rename/look.js', b'// old look\n')
            leftover = home / '.pane-rename-backup/.staging/pane-rename.previous'
            leftover.mkdir(parents=True)
            with self.assertRaisesRegex(ValueError, 'Leftover staging'):
                quietly(install.update, home)
            self.assertTrue(leftover.is_dir())
            self.assertEqual((home / 'mods/pane-rename/look.js').read_bytes(), b'// old look\n')

    def test_requires_an_installation(self):
        with tempfile.TemporaryDirectory() as tmp:
            with self.assertRaisesRegex(ValueError, 'No installation manifest'):
                quietly(install.update, Path(tmp))


if __name__ == '__main__': unittest.main()
